#!/usr/bin/env python3
"""Run the reproducible RENA conference prototype experiment."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
import numpy as np

from core.dataset import build_split
from core.model import train_base_model
from core.pipeline import ALGORITHMS, run_audit, run_full_comparison
from core.unlearning import fine_tuning_unlearn, gradient_ascent_unlearn, ground_truth_retrain, sisa_unlearn
from core.prism_unlearning import prism_unlearn
from core.evidence import EvidenceItem, evidence_from_audit
from core.recovery_stress_test import run_recovery_stress_test
from core.conformal_diagnostic import run_conformal_diagnostic
from core.llm_evidence_analyzer import DEFAULT_MODEL, LLMAPIError, PROVIDER, analyze_evidence

ROOT = Path(__file__).resolve().parent
RESULTS, FIGURES, DOCS = ROOT / "results", ROOT / "figures", ROOT / "docs"


def save_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")


def make_model(algorithm, split, original, sample_ids):
    if algorithm == "fine_tuning": return fine_tuning_unlearn(original, split.X_retain, split.y_retain)
    if algorithm == "gradient_ascent": return gradient_ascent_unlearn(original, split.X_forget, split.y_forget, split.X_retain, split.y_retain)
    if algorithm == "ground_truth_retraining": return ground_truth_retrain(split.X_retain, split.y_retain)
    if algorithm == "prism": return prism_unlearn(original, split)[0]
    ids = sample_ids[len(split.X_retain):]
    return sisa_unlearn(np.vstack([split.X_retain, split.X_forget]), np.concatenate([split.y_retain, split.y_forget]), ids, sample_ids)[0]
    raise ValueError(algorithm)


def svg_bars(path: Path, title: str, labels: list[str], values: list[float], ylabel: str) -> None:
    width, height, left, bottom = 760, 390, 65, 70
    chart_h, chart_w = 255, 650
    bars = []
    for i, (label, value) in enumerate(zip(labels, values)):
        x = left + i * (chart_w / len(labels)) + 15; bw = chart_w / len(labels) - 30
        h = max(0, min(1, value)) * chart_h; y = bottom + chart_h - h
        bars.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{bw:.1f}" height="{h:.1f}" fill="#31688e"/><text x="{x+bw/2:.1f}" y="{bottom+chart_h+18}" text-anchor="middle" font-size="11">{label}</text><text x="{x+bw/2:.1f}" y="{y-5:.1f}" text-anchor="middle" font-size="11">{value:.3f}</text>')
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}"><style>text{{font-family:Arial;fill:#202124}}</style><rect width="100%" height="100%" fill="white"/><text x="{width/2}" y="28" text-anchor="middle" font-size="18">{title}</text><line x1="{left}" y1="{bottom}" x2="{left}" y2="{bottom+chart_h}" stroke="#333"/><line x1="{left}" y1="{bottom+chart_h}" x2="{left+chart_w}" y2="{bottom+chart_h}" stroke="#333"/><text x="16" y="{bottom+chart_h/2}" transform="rotate(-90 16 {bottom+chart_h/2})" text-anchor="middle" font-size="12">{ylabel}</text>{''.join(bars)}</svg>'''
    path.parent.mkdir(parents=True, exist_ok=True); path.write_text(svg)


def write_summary_markdown(baseline, recovery, conformal, analyses):
    lines = ["# RENA conference experiment results", "", "## Real experimental results", "",
             "All numerical results below were generated by `python3 run_conference_experiment.py` on scikit-learn digits (1,797 8×8 grayscale images; 1,347 train / 450 held-out; 135 forget / 1,212 retain). The model is the repository's NumPy MLP (32, 16 hidden units).", "",
             "| Method | Verdict | Consensus | Agreement | Retain accuracy | Test accuracy | Forget accuracy |", "|---|---:|---:|---:|---:|---:|---:|"]
    for name, audit in baseline["results"].items():
        a, c = audit["accuracy"], audit["consensus"]
        lines.append(f"| {name} | {c['verdict']} | {c['consensus_score']:.4f} | {c['agreement']:.4f} | {a['retain']:.4f} | {a['test']:.4f} | {a['forget']:.4f} |")
    lines += ["", "## Methodology", "", "Four existing independent verifiers (membership attack, loss KS test, confidence analysis, bootstrap witness) remain the numerical sources. Their outputs are serialized as evidence IDs. Recovery stress testing applies direct, Gaussian-noise, random-mask, one-pixel spatial-shift, and contrast/brightness transformations to 8×8 standardized images, then measures a loss-based member/non-member AUC; normalized recoverability is `2 * abs(AUC - 0.5)`. Retain-versus-held-out is reported as a control. The retained set calibrates a supplementary probability prediction set; reported values are forget-label exclusion, retain-label exclusion, and their gap.", "", "## LLM methodology", "", "The analyzer receives structured evidence JSON only, uses Google Gemini structured JSON output, and validates the returned fields locally. It uses `GEMINI_API_KEY`; without that key it emits an explicitly labelled rule-based `FALLBACK`, which is not an LLM experiment and does not generate metrics.", "", "## Limitations and claims", "", "These results are limited to the tested digits dataset, split, model, and transformations. They provide evidence-grounded verification, not a proof or guarantee of machine unlearning. No adaptive attack or independent replication was performed.", "", "## Offline fallback results", ""]
    for method, result in analyses.items(): lines.append(f"- {method}: {result['analysis_mode']} — {result['overall_status']} ({result['claim_strength']})")
    lines += ["", "## Pending experiments", "", "If no API key was supplied, real LLM evidence analysis is `PENDING_REAL_API_EXECUTION`; adaptive attacks and external replication are also pending.", "", "## Exact command", "", "```bash", "python3 run_conference_experiment.py", "```"]
    (DOCS / "conference_results.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(); parser.add_argument("--reuse-baseline", action="store_true")
    parser.add_argument("--skip-llm", action="store_true", help="Run numerical experiments without replacing a prior Gemini artifact.")
    args = parser.parse_args(); RESULTS.mkdir(exist_ok=True); (RESULTS / "evidence").mkdir(exist_ok=True)
    baseline_path = RESULTS / "baseline_results.json"
    if args.reuse_baseline and baseline_path.exists(): baseline = json.loads(baseline_path.read_text())
    else:
        baseline = run_full_comparison(); save_json(baseline_path, baseline)

    split = build_split(); sample_ids = np.arange(len(split.X_retain) + len(split.X_forget))
    original = train_base_model(np.vstack([split.X_retain, split.X_forget]), np.concatenate([split.y_retain, split.y_forget]))
    all_recovery, all_conformal, analyses, ablation, rows = {}, {}, {}, {}, []
    evidence_index = 1
    for algorithm in ALGORITHMS:
        audit = baseline["results"][algorithm]
        items = evidence_from_audit(algorithm, audit, evidence_index); evidence_index += len(items)
        model = make_model(algorithm, split, original, sample_ids)
        recovery = run_recovery_stress_test(model, split); conformal = run_conformal_diagnostic(model, split)
        recovery_ids = []
        for record in recovery:
            eid = f"E{evidence_index:03d}"; evidence_index += 1; recovery_ids.append(eid)
            items.append(EvidenceItem(eid, "Recovery Stress Test", "normalized_recoverability", record["normalized_recoverability"], record["normalized_recoverability"], 1.0, None, [], ["A loss-based proxy under fixed transformations; not an adaptive attack."], {"algorithm": algorithm, **record}))
        conformal_id = f"E{evidence_index:03d}"; evidence_index += 1
        items.append(EvidenceItem(conformal_id, "Conformal-style diagnostic", "exclusion_gap", conformal["exclusion_gap"], None, None, None, [], [conformal["limitation"]], {"algorithm": algorithm, **conformal}))
        serialized = [x.to_dict() for x in items]; save_json(RESULTS / "evidence" / f"{algorithm}.json", serialized)
        if args.skip_llm:
            analysis = {"analysis_mode": "SKIPPED_PRESERVED_EXISTING", "overall_status": "NOT_ANALYZED", "claim_strength": "NOT_ANALYZED", "supporting_evidence_ids": [], "contradictory_evidence_ids": [], "missing_evidence": ["Gemini analysis deliberately skipped to preserve prior API artifact."]}
        else:
            try:
                analysis = analyze_evidence(serialized)
            except LLMAPIError as exc:
                error_result = {"analysis_mode": "API_ERROR", "provider": PROVIDER, "model": DEFAULT_MODEL, "algorithm": algorithm, "error": str(exc)}
                save_json(RESULTS / "llm_api_error.json", error_result)
                # Prevent an older FALLBACK/REAL_API artifact from being mistaken
                # for the outcome of this failed configured-key run.
                save_json(RESULTS / "claim_analysis.json", error_result)
                raise SystemExit(f"LLM API ERROR: {error_result['error']}")
        analysis["traceability"] = {"supporting": analysis["supporting_evidence_ids"], "contradictory": analysis["contradictory_evidence_ids"], "missing": analysis["missing_evidence"]}
        analyses[algorithm] = analysis; all_recovery[algorithm] = recovery; all_conformal[algorithm] = conformal
        c = audit["consensus"]
        ablation[algorithm] = {"original_consensus_only": {"verdict": c["verdict"], "score": c["consensus_score"]}, "consensus_plus_structured_evidence": {"evidence_items": 4, "contradictions": sum(bool(x["contradictions"]) for x in serialized[:4])}, "consensus_plus_recovery_stress_test": {"records": len(recovery), "direct_forget_recoverability": recovery[0]["normalized_recoverability"]}, "consensus_plus_conformal_diagnostic": conformal, "full_evidence_grounded_system": {"status": analysis["overall_status"], "claim_strength": analysis["claim_strength"], "llm_status": "PENDING_REAL_API_EXECUTION" if analysis["analysis_mode"] == "FALLBACK" else "REAL_API_EXECUTED"}}
        rows.append({"algorithm": algorithm, "consensus": c["consensus_score"], "agreement": c["agreement"], "retain_accuracy": audit["accuracy"]["retain"], "test_accuracy": audit["accuracy"]["test"], "forget_accuracy": audit["accuracy"]["forget"], "direct_recoverability": recovery[0]["normalized_recoverability"], "conformal_exclusion_gap": conformal["exclusion_gap"], "claim_status": analysis["overall_status"], "llm_mode": analysis["analysis_mode"]})
    save_json(RESULTS / "recovery_stress_results.json", all_recovery); save_json(RESULTS / "conformal_results.json", all_conformal)
    if not args.skip_llm:
        save_json(RESULTS / "claim_analysis.json", analyses)
    save_json(RESULTS / "ablation_results.json", ablation)
    with (RESULTS / "conference_summary.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys()); writer.writeheader(); writer.writerows(rows)
    labels = list(baseline["results"])
    svg_bars(FIGURES / "forget_vs_retain_performance.svg", "Forget vs retain accuracy", labels, [baseline["results"][x]["accuracy"]["forget"] for x in labels], "forget accuracy")
    svg_bars(FIGURES / "unlearning_method_comparison.svg", "Unlearning method consensus", labels, [baseline["results"][x]["consensus"]["consensus_score"] for x in labels], "consensus")
    ground_truth_forget = [x for x in all_recovery["ground_truth_retraining"] if x["comparison"] == "forget_vs_held_out"]
    svg_bars(FIGURES / "recovery_across_perturbations.svg", "Ground-truth recovery stress", [x["condition"] for x in ground_truth_forget], [x["normalized_recoverability"] for x in ground_truth_forget], "recoverability")
    svg_bars(FIGURES / "ablation_comparison.svg", "Evidence-grounded ablation", labels, [ablation[x]["consensus_plus_recovery_stress_test"]["direct_forget_recoverability"] for x in labels], "direct recoverability")
    write_summary_markdown(baseline, all_recovery, all_conformal, analyses)
    print(json.dumps({"methods": labels, "llm_modes": {k: v["analysis_mode"] for k, v in analyses.items()}, "results": str(RESULTS)}, indent=2))


if __name__ == "__main__": main()
